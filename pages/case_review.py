"""Case review: AI-prepared information is shown separately from the human reviewer's decision."""
import streamlit as st
from database import database as db
from utils import audit_log, privacy
from utils.ui import urgency_card, urgency_badge, status_badge, show_summary, show_questions, show_report_table
import pandas as pd


def _act(aid, status, action, label, comment, user):
    if status in ("More Info Requested", "Escalated") and not comment.strip():
        st.error("Please add a short comment so the next person knows what is needed.")
        return
    try:
        db.update_review(aid, status, user["display_name"], comment.strip())
        audit_log.log_action(user, action, comment.strip() or label, aid)
        st.success(f"Case #{aid}: {label}")
        st.rerun()
    except db.DatabaseError as e:
        st.error(f"Could not update the case. {e}")


def render():
    st.header("🗂️ Case Review")
    user = privacy.current_user()
    if not privacy.has_perm("view_dashboard"):
        st.error("Your role cannot open cases.")
        return
    try:
        df = db.list_assessments()
    except db.DatabaseError as e:
        st.error(f"Could not load cases. {e}")
        return
    if df.empty:
        st.info("No cases available.")
        return
    q = df.sort_values(["urgency_rank", "assessed_at"], ascending=[True, False])
    labels = {int(r.assessment_id): f"#{r.assessment_id} · {r.patient_id} · {r.urgency} · {r.review_status}" for r in q.itertuples()}
    if "selected_case" in st.session_state:
        st.session_state["cr_select"] = st.session_state.pop("selected_case")
    aid = st.selectbox("Select case", list(labels), format_func=labels.get, key="cr_select")
    try:
        c = db.get_case(aid)
    except db.DatabaseError as e:
        st.error(f"Could not load the case. {e}")
        return
    if not c:
        st.error("Case not found.")
        return
    st.markdown(f"### Case #{aid} · {c['patient_id']} &nbsp; {urgency_badge(c['urgency'])} &nbsp; {status_badge(c['review_status'])}", unsafe_allow_html=True)
    m = st.columns(5)
    m[0].metric("Age", c["age"])
    m[1].metric("Gender", c["gender"])
    m[2].metric("Language", c["language"])
    m[3].metric("Facility", c["facility_type"])
    m[4].metric("Assessed", str(c["assessed_at"])[:16])

    tabs = st.tabs(["🤖 AI-prepared information", "📄 Report & OCR", "📝 Triage note", "🧑‍⚕️ Professional review", "🧾 Audit trail"])
    with tabs[0]:
        st.caption("Advisory output generated by rules / AI. It is **not** a diagnosis.")
        urgency_card(c["urgency"], c["urgency_reasons"], "Review by qualified healthcare staff." if c["urgency"] != "URGENT REVIEW" else "Immediate review by a qualified healthcare professional.")
        a, b = st.columns(2)
        with a:
            st.markdown("**Original symptoms (as entered)**")
            st.code(c["original_text"] or "", language=None)
            st.caption(f"English working text · {c['translation_method']}")
            st.code(c["translated_text"] or "", language=None)
            if c["symptoms"]:
                st.dataframe(pd.DataFrame(c["symptoms"]).assign(negated=lambda d: d.negated.map({0: "reported", 1: "denied"})),
                             hide_index=True, width="stretch")
        with b:
            show_summary(c["summary"])
        st.subheader("Follow-up questions")
        show_questions(c["questions"], c["language"])
    with tabs[1]:
        if c["report"]:
            st.caption(f"File: {c['report']['filename'] or 'n/a'} · flagged values: {c['report']['flagged_count']}")
            show_report_table(c["report"].get("parsed"))
            with st.expander("OCR output (raw text)"):
                st.code(c["report"]["ocr_text"], language=None)
        else:
            st.info("No report was uploaded for this case.")
    with tabs[2]:
        n = c["note"] or {}
        st.markdown('<div class="ai-box">🤖 AI-generated draft</div>', unsafe_allow_html=True)
        with st.expander("View original AI note", expanded=not n.get("edited_note")):
            st.code(n.get("ai_note", ""), language=None)
        cur = n.get("edited_note") or n.get("ai_note", "")
        edited = st.text_area("Editable reviewer version", cur, height=380, key=f"note_{aid}", disabled=not privacy.has_perm("edit_note"))
        if n.get("edited_by"):
            st.caption(f"Last edited by {n['edited_by']} at {n['edited_at']}")
        if st.button("💾 Save edited note", disabled=not privacy.has_perm("edit_note")):
            try:
                db.save_note_edit(aid, edited, user["display_name"])
                audit_log.log_action(user, "note_edited", "Triage note edited by reviewer", aid)
                st.success("Note saved.")
            except db.DatabaseError as e:
                st.error(f"Could not save the note. {e}")
    with tabs[3]:
        st.markdown('<div class="human-box">🧑‍⚕️ Decisions below are made by a human reviewer. The AI cannot mark a patient as diagnosed.</div>', unsafe_allow_html=True)
        if c["reviewer"]:
            st.caption(f"Last action by {c['reviewer']} at {c['reviewed_at']}" + (f" · comment: {c['reviewer_comment']}" if c["reviewer_comment"] else ""))
        comment = st.text_area("Reviewer comment", key=f"cmt_{aid}", placeholder="Required for 'Request More Information' and 'Escalate'.")
        b1, b2, b3 = st.columns(3)
        if b1.button("✅ Mark Reviewed", width="stretch", disabled=not privacy.has_perm("mark_reviewed"),
                     help="Records that a human has reviewed the AI-prepared note. It is not a diagnosis."):
            _act(aid, "Reviewed", "marked_reviewed", "marked as reviewed.", comment, user)
        if b2.button("❓ Request More Information", width="stretch", disabled=not privacy.has_perm("request_info")):
            _act(aid, "More Info Requested", "requested_more_info", "more information requested.", comment, user)
        if b3.button("🚑 Escalate to Qualified Professional", width="stretch", disabled=not privacy.has_perm("escalate")):
            _act(aid, "Escalated", "escalated", "escalated to a qualified professional.", comment, user)
        if not (privacy.has_perm("mark_reviewed") and privacy.has_perm("escalate")):
            st.caption(f"Role '{user['role']}' has limited actions (role-based access mockup). Switch role in the sidebar.")
    with tabs[4]:
        logs = audit_log.get_logs(aid)
        st.dataframe(pd.DataFrame(logs).drop(columns=["assessment_id"]) if logs else pd.DataFrame({"info": ["No log entries"]}),
                     hide_index=True, width="stretch")
